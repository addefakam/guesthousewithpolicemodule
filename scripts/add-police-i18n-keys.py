"""
Add i18n keys for all 12 police module pages to en.json, am.json, om.json.
For am.json and om.json, English values are used as placeholders.
"""
import json
import os

LOCALE_DIR = "/home/z/my-project/src/i18n/locales"

def add_keys_to_file(filename, new_namespaces):
    filepath = os.path.join(LOCALE_DIR, filename)
    with open(filepath, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    for ns, keys in new_namespaces.items():
        if ns in data:
            print(f"  {filename}: '{ns}' already exists with {len(data[ns])} keys, merging...")
            data[ns].update(keys)
        else:
            data[ns] = keys
            print(f"  {filename}: Added '{ns}' with {len(keys)} keys")
    
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"  {filename}: Written successfully")

