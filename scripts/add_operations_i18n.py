def update_locale(filepath, operations_data):
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
    
    # Merge operations namespace
    if 'operations' in data:
        # Update existing, add new
        for k, v in operations_data.items():
            data['operations'][k] = v
    else:
        data['operations'] = operations_data
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    print(f"Updated {filepath}: {len(operations_data)} keys in operations namespace")


# Update all 3 locale files
for locale, ops_data in [('en', OPERATIONS_EN), ('am', OPERATIONS_AM), ('om', OPERATIONS_OM)]:
    filepath = f"{LOCALE_DIR}/{locale}.json"
    update_locale(filepath, ops_data)

print("\nDone!")
